"""Integrate a supplied textured character using explicitly identified stock eyes.

Source eye centers must be symmetric and subject must already face -Y. Explicit
mapping avoids guessing mesh names or silently calibrating from facial geometry.
"""
import argparse
from dataclasses import asdict
import json
from pathlib import Path
import sys
import bpy
from mathutils import Vector,Matrix
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'build'))
sys.path.insert(0,str(ROOT/'wrapper'))
from fixture_scene import build
import eyes


def integrate(source,mapping_path,output):
    mapping=json.loads(mapping_path.read_text(encoding='utf-8'))
    if mapping.get('faces_negative_y') is not True:
        raise ValueError('Confirm source orientation in character mapping')
    if not mapping.get('attribution') or 'REPLACE' in mapping['attribution']:
        raise ValueError('Record source asset names and licenses in mapping attribution')
    build(output.parent/'fixture_reference.blend')
    with bpy.data.libraries.load(str(source),link=False) as (available,loaded):
        loaded.objects=available.objects
    imported=[obj for obj in loaded.objects if obj is not None]
    for obj in imported:
        if obj.type in {'CAMERA','LIGHT'}: continue
        if obj.name not in bpy.context.scene.objects:
            bpy.context.collection.objects.link(obj)
    bpy.context.view_layer.update()
    def selected(side):
        name=mapping['eyes'][side]
        matches=[o for o in imported if o.name==name]
        if len(matches)!=1: raise ValueError(f'Cannot identify stock eye {name}')
        return matches[0]
    stock={side:selected(side) for side in 'LR'}
    centers={s:sum((o.matrix_world@Vector(p) for p in o.bound_box),Vector())/8 for s,o in stock.items()}
    ipd=(centers['L']-centers['R']).length
    if not .058<=ipd<=.068: raise ValueError(f'Measured IPD {ipd} m outside 58–68 mm; normalize source units first')
    separation=centers['L']-centers['R']
    if separation.x<=0 or abs(separation.y)>.00005 or abs(separation.z)>.00005:
        raise ValueError('Mapped anatomical eyes must be aligned along +X')
    midpoint=(centers['L']+centers['R'])/2
    for obj in imported:
        if obj.parent is None:
            obj.matrix_world=Matrix.Translation(-midpoint)@obj.matrix_world
        if obj.type in {'CAMERA','LIGHT'}: obj.hide_render=True
    for obj in stock.values(): obj.hide_render=True; obj.hide_viewport=True
    bpy.data.objects['Face proxy'].hide_render=True
    # Move each fixture eye's rest mesh and bone to measured production spacing.
    rig=bpy.data.objects[bpy.context.scene['apollo_armature']]
    eyes.reset()
    for pb in rig.pose.bones: pb.matrix_basis=Matrix.Identity(4)
    bpy.context.view_layer.objects.active=rig
    rig.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    for side,sign in [('L',1),('R',-1)]:
        bone=rig.data.edit_bones['eye.'+side]
        delta=sign*(ipd-.063)/2
        bone.head.x+=delta; bone.tail.x+=delta
        for prefix in ['Sclera.','Iris.','Pupil.']:
            for vertex in bpy.data.objects[prefix+side].data.vertices: vertex.co.x+=delta
    bpy.ops.object.mode_set(mode='OBJECT')
    cfg=eyes.Config(ipd=ipd)
    scene=bpy.context.scene
    scene['apollo_calibration']=json.dumps(asdict(cfg))
    scene['apollo_fixture']=False
    scene['apollo_source']=source.name
    eyes._RIG=None
    eyes.reset()
    for image in bpy.data.images:
        if image.size[0]>2048 or image.size[1]>2048:
            scale=2048/max(image.size)
            image.scale(max(1,int(image.size[0]*scale)),max(1,int(image.size[1]*scale)))
    bpy.ops.file.pack_all()
    output.parent.mkdir(parents=True,exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=str(output),compress=True)
    (output.parent/'ATTRIBUTION.md').write_text(mapping['attribution']+'\n\nProcedural eyes: generated by Apollo.\n',encoding='utf-8')
    print('Production candidate saved; visual and pixel verification still required:',output)

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--source',type=Path,required=True)
    p.add_argument('--mapping',type=Path,required=True)
    p.add_argument('--out',type=Path,required=True)
    args=p.parse_args(sys.argv[sys.argv.index('--')+1:])
    integrate(args.source,args.mapping,args.out)
